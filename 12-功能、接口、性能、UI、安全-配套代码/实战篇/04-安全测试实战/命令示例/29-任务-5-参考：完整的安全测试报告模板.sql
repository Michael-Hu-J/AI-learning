## 三、发现的漏洞

### [P0] 未发现
### [P1] 未发现
### [P2] 搜索框 XSS 风险
- **描述：** 搜索框输入 `<img src=x onerror=alert(1)>` 时，脚本被执行
- **影响：** 攻击者可窃取用户 Cookie 或篡改页面内容
- **建议：** 后端使用 `html.escape()` 或 `bleach.clean()` 对输出做转义
### [P3] 接口未做限流
- **描述：** 登录接口 1 秒内调 100 次全部返回 200
- **影响：** 攻击者可进行暴力破解攻击
- **建议：** 添加限流中间件（如 Flask-Limiter）

