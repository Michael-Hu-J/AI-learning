# 排查路径（从现象到根因）：
# 
# 现象：压测时 TPS 在某个值上不去了
# 
# 第1步：看资源使用
#   MySQL CPU高 → 慢查询 → 加索引 / 优化SQL
#   Redis CPU高 → 连接池满 / 大key → 扩容 / 拆分key
#   应用CPU高 → 线程满 / GC频繁 → 调线程池 / 调JVM参数
#   带宽满 → 响应体太大 → 压缩 / 分页
#
# 第2步：如果资源都正常
#   可能是应用代码里有串行操作（比如 synchronized）
#   或者是数据库连接池太小
#
# 第3步：用链路追踪（APM工具）
#   看请求的耗时分布在哪一段
#   数据库查询？Redis缓存？HTTP调用外部服务？
